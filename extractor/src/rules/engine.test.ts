import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import type { DocumentStructure } from "@nordic/db/document-structure";
import { evidenceRefProblems, type RuleCandidate, type RuleIssue, type RuleOutput } from "@nordic/db/rule-output";
import { runRules, type EngineInput } from "./engine";
import { elementString } from "./strategies";
import { PAGE_TYPES, RULES } from "./registry";
import type { Rule } from "./types";

// PR 2b acceptance on SYNTHETIC fixtures shaped like the Stockholm University
// and KTH pages (crawler/test/fixtures/*.html → structures/*.json, generated by
// the crawler). The page URLs are the real registered URLs, used only as
// context: they choose the site rules and page type, never the intake.

const fixture = (name: string): DocumentStructure =>
  JSON.parse(readFileSync(new URL(`../../../crawler/test/fixtures/structures/${name}.json`, import.meta.url), "utf8"));
const HASH = "c".repeat(64);
const SU_2026 = "https://www.su.se/english/education/course-catalogue/sp/sprom?semester=HT2026&eventcode=43006";
const SU_2027 = "https://www.su.se/english/education/course-catalogue/sp/sprom?semester=HT2027&eventcode=43003";
const KTH = "https://www.kth.se/en/studies/master/industrial-management";
const input = (structure: DocumentStructure, pageUrl: string, extra: Partial<EngineInput> = {}): EngineInput =>
  ({ documentId: "doc-1", structureId: "struct-1", structureHash: HASH, structure, pageUrl, country: "sweden", ...extra });
const run = (i: EngineInput, rules: readonly Rule[] = RULES) => runRules(i, rules, PAGE_TYPES);
const candidates = (out: RuleOutput[], factType?: string) => out.filter((o): o is RuleCandidate => o.kind === "candidate" && (!factType || o.factType === factType));
const issues = (out: RuleOutput[], kind: RuleIssue["kind"]) => out.filter((o): o is RuleIssue => o.kind === kind);

describe("Stockholm-University-like intake page", () => {
  const out = run(input(fixture("programme-intake"), SU_2026));
  it("1. reads label/value pairs, kept verbatim with evidence on the pair", () => {
    const [language] = candidates(out, "teaching_language");
    expect(language).toMatchObject({ ruleId: "su.teaching_language.pair", method: "pair", raw: { text: "English" }, normalized: null,
      evidence: { ref: "p1", field: "canonical", excerpt: "Language: English" }, intake: null, applicability: null });
  });
  it("10. tuition is neither programme-wide nor intake-wide without evidence, though it sits under the intake heading", () => {
    const fees = candidates(out, "tuition_fee");
    expect(fees.map((f) => [f.raw.text, f.normalized?.number ?? null, f.normalized?.period ?? null, f.intake, f.applicability])).toEqual([
      ["100000 SEK", "100000", "total", null, null],
      ["50000 SEK", null, null, null, null],
    ]);
    expect(fees[1].notes.join(" ")).toMatch(/period_unknown/);
    expect(fees.every((f) => f.evidence.excerpt.startsWith("Applies to citizens from outside EU"))).toBe(true);
  });
  it("4. a mention of ANOTHER intake (autumn 2027) is never used: the 2026 page has no 2027 candidate", () => {
    expect(JSON.stringify(out)).not.toMatch(/"year":2027/);
    expect(candidates(out).filter((c) => c.intake).map((c) => c.intake?.year)).toEqual([]);
    // The application period is "Closed for application" on this intake: nothing invented.
    expect(issues(out, "not_found").map((i) => i.factType)).toEqual(["application_period"]);
  });
  it("reads credits under the intake heading and the stated duration, never the degree name", () => {
    expect(candidates(out, "programme_credits")[0]).toMatchObject({ raw: { text: "60 credits" }, normalized: { number: "60", unit: "credits" }, intake: null });
    expect(candidates(out, "programme_duration")[0]).toMatchObject({ raw: { text: "two years" }, normalized: { number: "24", unit: "months" } });
  });
  it("on the next intake page, the application period gets the intake from its own heading", () => {
    const next = run(input(fixture("programme-intake-next"), SU_2027));
    const [period] = candidates(next, "application_period");
    expect(period).toMatchObject({ raw: { text: "Application opens 16 October 2026" }, applicability: "intake",
      intake: { label: "Autumn 2027", year: 2027, term: "autumn", month: null, from: "heading", evidence: { field: "text", excerpt: "Autumn 2027" } } });
    expect(period.intake?.from === "heading" && period.intake.evidence.ref).toBe(fixture("programme-intake-next").headings.find((h) => h.text.startsWith("Autumn 2027"))?.ref);
  });
});

describe("KTH-like programme page", () => {
  const out = run(input(fixture("programme-deadlines"), KTH));
  it("2 + 5. reads one line under the deadline heading; \"15 January\" stays an unresolved date", () => {
    const [deadline] = candidates(out, "application_deadline");
    expect(deadline).toMatchObject({ method: "section_lines", raw: { text: "15 January" }, normalized: null, applicability: "intake",
      evidence: { ref: "b1", field: "text", excerpt: "15 January: Last day to apply" },
      intake: { label: "August 2027", year: 2027, term: null, month: 8, from: "heading" } });
    expect(deadline.notes.join(" ")).toMatch(/year_missing/);
  });
  it("the opening line keeps its stated year as text", () => {
    expect(candidates(out, "application_period")[0]).toMatchObject({ raw: { text: "16 October (2026): Application opens" }, intake: { month: 8, year: 2027 } });
  });
  it("3. different structures give the same fact types (pair on SU, sentence on KTH)", () => {
    const su = run(input(fixture("programme-intake"), SU_2026));
    for (const type of ["teaching_language", "programme_credits", "programme_duration"]) {
      expect(candidates(su, type).length).toBeGreaterThan(0);
      expect(candidates(out, type).length).toBeGreaterThan(0);
    }
    expect(candidates(su, "teaching_language")[0].method).toBe("pair");
    expect(candidates(out, "teaching_language")[0]).toMatchObject({ method: "sentence", raw: { text: "English" } });
    expect(candidates(out, "programme_credits")[0].normalized).toMatchObject({ number: "120", unit: "ECTS" });
    expect(candidates(out, "programme_duration")[0].normalized).toMatchObject({ number: "24", unit: "months" });
  });
});

describe("conflicts, absence and order", () => {
  it("6. two different statements for one fact type are ambiguous; nothing is chosen", () => {
    const s = fixture("programme-intake");
    const twice = { ...s, pairs: [...s.pairs, { ...s.pairs[1], ref: "p9", value: "The complete course: 120000 SEK." }] };
    const out = run(input(twice, SU_2026));
    expect(candidates(out, "tuition_fee")).toEqual([]);
    const [amb] = issues(out, "ambiguous");
    expect(amb).toMatchObject({ factType: "tuition_fee", ruleIds: ["su.tuition_fee.pair"] });
    expect(amb.candidates?.map((c) => c.evidence.ref)).toEqual(["p2", "p2", "p9"]);
  });
  it("the same statement repeated in another element is a duplicate, not a conflict", () => {
    const s = fixture("programme-intake");
    const out = run(input({ ...s, pairs: [...s.pairs, { ...s.pairs[0], ref: "p9" }] }, SU_2026));
    expect(candidates(out, "teaching_language").map((c) => c.evidence.ref)).toEqual(["p1"]);
    expect(issues(out, "ambiguous")).toEqual([]);
  });
  it("7. a page without the values reports not_found per fact type", () => {
    const empty: DocumentStructure = { ...fixture("programme-deadlines"), headings: [], blocks: [], pairs: [], tables: [], links: [] };
    const out = run(input(empty, KTH));
    expect(candidates(out)).toEqual([]);
    expect(issues(out, "not_found").map((i) => i.factType)).toEqual(["application_deadline", "application_period", "programme_credits", "programme_duration", "teaching_language"]);
  });
  it("8. the order of rules does not change the output", () => {
    const i = input(fixture("programme-intake-next"), SU_2027);
    const expected = JSON.stringify(run(i));
    for (const order of [[...RULES].reverse(), [...RULES.slice(3), ...RULES.slice(0, 3)]]) expect(JSON.stringify(run(i, order))).toBe(expected);
  });
  it("9. every candidate carries valid evidence that is inside the element it names", () => {
    const pages: [string, string][] = [["programme-intake", SU_2026], ["programme-intake-next", SU_2027], ["programme-deadlines", KTH]];
    for (const [name, url] of pages) {
      const s = fixture(name);
      const all = run(input(s, url)).flatMap((o) => (o.kind === "candidate" ? [o] : o.candidates ?? []));
      expect(all.length).toBeGreaterThan(0);
      for (const c of all) {
        expect(evidenceRefProblems(c.evidence)).toEqual([]);
        expect(elementString(s, c.evidence)).toContain(c.evidence.excerpt);
        if (c.intake?.from === "heading") expect(elementString(s, c.intake.evidence)).toContain(c.intake.evidence.excerpt);
        expect(c).toMatchObject({ derivation: null, rulesetVersion: expect.stringMatching(/^ruleset-[0-9a-f]{12}$/) });
      }
    }
  });
});

describe("matching and precedence (synthetic rules)", () => {
  const SITE = "https://uni.example.test";
  const page = `${SITE}/programmes/example`;
  const types = [{ source: SITE, type: "programme", url: /^https:\/\/uni\.example\.test\/programmes\/[a-z]+$/ }];
  const rule = (id: string, scope: Rule["scope"], labels: string[], extra: Partial<Rule> = {}): Rule => ({
    id, version: 1, enabled: true, mode: "shadow", priority: 0, scope, field: "teaching_language",
    strategy: { kind: "pair", labels }, normalize: { kind: "text" }, intake: { from: "none" }, evidence: "value", ...extra });
  const s: DocumentStructure = { ...fixture("programme-table"), pairs: [
    { ref: "p1", domPath: "x", label: "Language", value: "English", section: [], from: "label_value", labelPath: "x", valuePath: "x" },
    { ref: "p2", domPath: "y", label: "Teaching language", value: "Swedish", section: [], from: "label_value", labelPath: "y", valuePath: "y" },
  ] };
  const go = (rules: Rule[], url = page) => runRules(input(s, url), rules, types);
  it("the most specific rule wins; a less specific one is only a fallback", () => {
    const out = go([rule("x.global", {}, ["Language"]), rule("x.site", { source: SITE }, ["Teaching language"])]);
    expect(candidates(out).map((c) => [c.ruleId, c.raw.text])).toEqual([["x.site", "Swedish"]]);
    expect(issues(out, "ambiguous")).toEqual([]);
  });
  it("the fallback answers when the specific rule finds nothing", () => {
    const out = go([rule("x.global", {}, ["Language"]), rule("x.site", { source: SITE }, ["Medium"])]);
    expect(candidates(out).map((c) => c.ruleId)).toEqual(["x.global"]);
  });
  it("same level, same priority, different values → ambiguous; higher priority wins", () => {
    expect(issues(go([rule("x.a", { source: SITE }, ["Language"]), rule("x.b", { source: SITE }, ["Teaching language"], { priority: 0 })]), "ambiguous")).toHaveLength(1);
    const out = go([rule("x.a", { source: SITE }, ["Language"]), rule("x.b", { source: SITE }, ["Teaching language"], { priority: 1 })]);
    expect(candidates(out).map((c) => c.ruleId)).toEqual(["x.b"]);
  });
  it("overrides remove the named rule; disabled rules and other scopes do not run", () => {
    const out = go([rule("x.site", { source: SITE }, ["Language"]), rule("x.page", { source: SITE, pageType: "programme" }, ["Teaching language"], { overrides: [] }),
      rule("x.other", { source: "https://other.example.test" }, ["Language"]), rule("x.off", { source: SITE, pageType: "programme" }, ["Language"], { enabled: false, priority: 9 })]);
    expect(candidates(out).map((c) => c.ruleId)).toEqual(["x.page"]);
    const overridden = go([rule("x.a", { source: SITE }, ["Language"]), rule("x.b", { source: SITE }, ["Teaching language"], { overrides: ["x.a"] })]);
    expect(candidates(overridden).map((c) => c.ruleId)).toEqual(["x.b"]);
  });
  it("table cells: evidence names the cell", () => {
    const t = fixture("programme-table");
    const credits = rule("x.table", { source: SITE }, [], { field: "programme_credits", strategy: { kind: "table", columnHeader: "ECTS", rowLabel: "4" }, normalize: { kind: "credits" }, evidence: "cell" });
    // "30" has no credit unit: the normalizer refuses rather than assume one.
    const refused = runRules(input(t, page), [credits], types);
    expect(candidates(refused)).toEqual([]);
    expect(issues(refused, "normalize_failed")[0].detail).toMatch(/^t2: no_value/);
    const course = rule("x.table.text", { source: SITE }, [], { strategy: { kind: "table", columnHeader: "Course", rowLabel: "4" }, evidence: "cell" });
    expect(candidates(runRules(input(t, page), [course], types))[0])
      .toMatchObject({ method: "table", raw: { text: "Thesis" }, evidence: { ref: "t2", field: "cell", cell: [1, 1], excerpt: "Thesis" } });
  });
  it("JSON-LD: an ISO 8601 duration is not converted (normalize_failed, nothing assumed)", () => {
    const r = rule("x.jsonld", { source: SITE }, [], { field: "programme_duration", strategy: { kind: "json_ld", type: "EducationalOccupationalProgram", path: ["timeToComplete"] }, normalize: { kind: "duration" }, evidence: "text" });
    const out = runRules(input(fixture("programme-rendered"), page), [r], types);
    expect(candidates(out)).toEqual([]);
    expect(issues(out, "normalize_failed")[0].detail).toMatch(/^sd0\.0: no_value/);
  });
  it("an intake from the page binding only when the caller gives one; otherwise intake_unresolved", () => {
    const period = rule("x.period", { source: SITE }, ["Language"], { field: "application_period", intake: { from: "page" } });
    expect(issues(runRules(input(s, page), [period], types), "intake_unresolved")).toHaveLength(1);
    const pageIntake = { label: "Autumn 2027", year: 2027, term: "autumn" as const, month: null, from: "page" as const, record: { programmePageId: "pp1", intakeId: "in1" } };
    const [c] = candidates(runRules(input(s, page, { pageIntake }), [period], types));
    expect(c).toMatchObject({ intake: pageIntake, applicability: "intake" });
  });
  it("a heading that names no term or month leaves the intake unresolved, with the words kept", () => {
    const structure: DocumentStructure = { ...s, pairs: [], headings: [{ ref: "h1", domPath: "h", level: 2, text: "Intake 2027", section: [] }],
      blocks: [{ ref: "b1", domPath: "b", kind: "p", text: "Application opens 16 October 2026", section: ["Intake 2027"] }] };
    const r: Rule = { ...rule("x.opens", { source: SITE }, []), field: "application_period", strategy: { kind: "sentence", pattern: /^Application opens .+$/ },
      intake: { from: "heading", pattern: /^Intake (?<year>\d{4})(?<term>)$/ }, evidence: "text" };
    const [issue] = issues(runRules(input(structure, page), [r], types), "intake_unresolved");
    expect(issue).toMatchObject({ factType: "application_period", intakeText: "Intake 2027" });
  });
});
